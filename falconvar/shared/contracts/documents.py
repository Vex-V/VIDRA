@dataclass
class Produced:
    """What a component actually wrote.

    A bare path would be shorter and say less. This reports the real output:
    no ``store`` on a run with the frame store off, no ``transcript`` on a
    silent file, and the stats a progress callback wants -- so a caller learns
    what happened rather than assuming from what it asked for.
    """

    #: Which video, and **the answer rather than the argument**: `media` may
    #: mint a new id when a different file wants a taken one, so later calls
    #: read it from here.
    video_id: str
    #: Which component produced this. `boundaries.evidence` answers as
    #: `boundaries.video` or `boundaries.audio`, naming which modality supplied
    #: the cuts -- which is not knowable before it runs.
    component: str
    #: `{artifact name: where it went}`. Lists what *was* written rather than
    #: what could be: a run with no frame store has a manifest and no store,
    #: and a caller should learn that from here rather than by looking.
    artifacts: dict[str, str] = field(default_factory=dict)
    #: The component's headline numbers. What is in here is the component's
    #: business; `component` says whose vocabulary to read it in.
    stats: dict[str, Any] = field(default_factory=dict)
    #: What did not happen, and it is an answer rather than an absence --
    #: `boundaries.evidence` under `uniform` returns `skipped: [evidence]`
    #: rather than nothing, so one call answers the same way over HTTP and from
    #: an import.
    skipped: list[str] = field(default_factory=list)

    def path(self, name: str) -> str:
        return self.artifacts[name]

    def as_dict(self) -> dict[str, Any]:
        return {"video_id": self.video_id, "component": self.component,
                "artifacts": self.artifacts,
                "stats": self.stats, "skipped": self.skipped}


def same_video(**documents: Any) -> str:
    """The one id these documents agree on, or a refusal naming the argument.

    Here because it is a fact about documents rather than about storage: every
    one of them carries its own `video_id`, and a component works on one
    video. Needs nothing but that attribute, so it does not cost this module
    the import-nothing rule.

    Addressed by video id this could not happen -- `paths.artifact(id, name)`
    is a join, so two artifacts read under one id are that video's by
    construction. Addressed by path it can, and a pipeline keeping every file
    in one folder makes it rare rather than impossible. So the check is
    written down once, where a caller wiring components by hand also gets it.
    """
    seen = {name: doc.video_id for name, doc in documents.items()
            if doc is not None}
    ids = set(seen.values())
    if len(ids) > 1:
        detail = ", ".join(f"{name}={vid!r}" for name, vid in sorted(seen.items()))
        raise Refused(
            f"these documents are not the same video: {detail}. "
            f"Each carries its own id, and a component works on one video.")
    return next(iter(ids)) if ids else ""


