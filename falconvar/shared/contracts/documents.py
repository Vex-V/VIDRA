# 4 · timeline  --  THE GRID
# --------------------------------------------------------------------------

@dataclass
class Timeline:
    """Where every chunk starts and ends, and what decided it.

    `chunk_id` is the index into ``spans``, and it is a key three other
    documents inherit. A chunk is simultaneously the unit a describer
    summarises, the unit a transcript is cut into and the unit retrieval
    returns -- so if the picture and the soundtrack disagreed about where a
    boundary falls, one query would return two different clips with no honest
    way to say which is the answer.
    """

    #: Which video this grid divides.
    video_id: str
    #: `(start_s, end_s)` per chunk, in order and contiguous. The chunk id is
    #: the index into this list, which is why nothing may renumber it.
    spans: list[tuple[float, float]]
    #: How the boundaries were decided: `uniform`, `scene`, `vad` or `speaker`.
    policy: str = "uniform"                       # uniform|scene|vad|speaker
    #: The settings this grid was built under -- the chunk length, the floor
    #: and ceiling, and whatever the evidence pass recorded.
    params: dict[str, Any] = field(default_factory=dict)
    #: "video", "audio", or "grid" when the policy is arithmetic and neither
    #: modality had to run. Recorded because a reader otherwise cannot tell a
    #: propagated boundary from a natively derived one.
    derived_from: str = "grid"

    def __len__(self) -> int:
        return len(self.spans)

    @property
    def duration_s(self) -> float:
        return self.spans[-1][1] if self.spans else 0.0

    def bounds_of(self, chunk_id: int) -> tuple[float, float]:
        """Start and end. Never an open end -- a supplied grid is complete, and
        that is the difference from a chunker deriving one as it streams."""
        return self.spans[chunk_id]

    def index_at(self, ts: float) -> Optional[int]:
        """Which chunk contains ``ts``. The last chunk owns its own end."""
        for index, (start, end) in enumerate(self.spans):
            if start <= ts < end:
                return index
        if self.spans and ts == self.spans[-1][1]:
            return len(self.spans) - 1
        return None

    def nearest(self, ts: float) -> int:
        """``index_at``, but never None.

        Media time outside the grid happens at the tail: the audio stream is
        routinely a few milliseconds shorter than the video one, so the last
        frames of a file can fall past a grid derived from the soundtrack. The
        nearest edge chunk owns them rather than the frame being dropped or a
        chunk being invented for it.
        """
        index = self.index_at(ts)
        if index is not None:
            return index
        if not self.spans:
            raise Refused("an empty timeline contains no chunk")
        return 0 if ts < self.spans[0][0] else len(self.spans) - 1

    def fingerprint(self) -> str:
        """A hash of the grid and the policy that produced it.

        Every document cut on this grid records it. If two disagree, they were
        cut on different grids and `chunk_id` means two different things --
        which becomes a comparison a reader can make rather than a drift that
        nothing reports.
        """
        return _hash({
            "spans": [[_round(s), _round(e)] for s, e in self.spans],
            "policy": self.policy,
            "params": self.params,
        })

    def as_dict(self) -> dict[str, Any]:
        return {
            "document": "timeline", "version": 1,
            "video_id": self.video_id,
            "policy": self.policy,
            "derived_from": self.derived_from,
            "params": self.params,
            "fingerprint": self.fingerprint(),
            "duration_s": _round(self.duration_s),
            "chunk_count": len(self.spans),
            "chunks": [{"chunk_id": i, "start_ts": _round(s), "end_ts": _round(e)}
                       for i, (s, e) in enumerate(self.spans)],
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "Timeline":
        return cls(
            video_id=d["video_id"],
            spans=[(float(c["start_ts"]), float(c["end_ts"]))
                   for c in sorted(d["chunks"], key=lambda c: c["chunk_id"])],
            policy=d.get("policy", "uniform"),
            params=d.get("params", {}),
            derived_from=d.get("derived_from", "grid"),
        )


# --------------------------------------------------------------------------
# 5 · manifest  --  which frames were kept, why, and how to fetch them again
# --------------------------------------------------------------------------

@dataclass
class Manifest:
    """What each sampler kept from each chunk.

    **No `start_ts` / `end_ts`.** Those belong to the grid, and one copy of the
    grid is the whole point -- `falconvar` stores the spans in `video_chunks`
    *and* `audio_chunks` with nothing constraining them to agree. A reader
    joins on `chunk_id` and gets them from `timeline.json`.

    ``manifest_fingerprint`` is a hash of the source minus its uri, and the
    config minus the frame store. So it is known before the first chunk exists,
    survives the video and the store being moved, and changes when the sampling
    changes. Staleness downstream is a comparison against it, never a deletion:
    re-ingesting costs seconds where describing costs inference.
    """

    #: Which video was ingested.
    video_id: str
    #: The grid this was cut on. Everything cut on a grid records this, so two
    #: documents that disagree were cut on different ones and `chunk_id` means
    #: two different things.
    timeline_fingerprint: str
    #: What was decoded: the path, the container, the duration and the video
    #: stream's own facts. This is what `recovery/` rebuilds a store from,
    #: which is why it is copied here rather than referenced.
    source: dict[str, Any] = field(default_factory=dict)
    #: The decimator, every sampler's own configuration, and where frames went.
    #: Authoritative: `recovery/` reads this and imports nothing from the
    #: pipeline, so a default living in code rather than here would go
    #: untested.
    config: dict[str, Any] = field(default_factory=dict)
    #: Frames decimated, frames sampled, chunks, and -- when frames were kept
    #: -- how many files and how many megabytes. `frames_sampled` is picks and
    #: `stored_frames` is files, and they are different numbers.
    stats: dict[str, Any] = field(default_factory=dict)
    #: [{chunk_id, decimated_frames, samplers: {id: {frame_count, frames[]}}}]
    chunks: list[dict[str, Any]] = field(default_factory=list)

    def fingerprint(self) -> str:
        return _hash({
            "source": {k: v for k, v in self.source.items() if k != "path"},
            "config": {k: v for k, v in self.config.items()
                       if k != "frame_store"},
        })

    def sampler_ids(self) -> list[str]:
        return [s["id"] for s in self.config.get("samplers", [])]

    def frames_of(self, chunk_id: int, sampler_id: str) -> list[dict[str, Any]]:
        for chunk in self.chunks:
            if chunk["chunk_id"] == chunk_id:
                block = chunk.get("samplers", {}).get(sampler_id)
                return list(block["frames"]) if block else []
        return []

    def as_dict(self) -> dict[str, Any]:
        return {
            "document": "manifest", "version": 1,
            "video_id": self.video_id,
            "timeline_fingerprint": self.timeline_fingerprint,
            "manifest_fingerprint": self.fingerprint(),
            "source": self.source,
            "config": self.config,
            "stats": self.stats,
            "chunks": self.chunks,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "Manifest":
        return cls(video_id=d["video_id"],
                   timeline_fingerprint=d.get("timeline_fingerprint", ""),
                   source=d.get("source", {}), config=d.get("config", {}),
                   stats=d.get("stats", {}), chunks=d.get("chunks", []))


